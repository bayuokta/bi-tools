  function translate(text) {
    var value = String(text == null ? "" : text);
    if (current() !== "id") return value;
    return has(id, value) ? id[value] : value;
  }

  function translateServer(text) {
    var value = String(text == null ? "" : text);
    if (current() !== "en" || !value) return value;
    if (has(serverExact, value)) return serverExact[value];
    for (var index = 0; index < serverPatterns.length; index += 1) {
      var pattern = serverPatterns[index][0];
      if (pattern.test(value)) return value.replace(pattern, serverPatterns[index][1]);
    }
    return value;
  }


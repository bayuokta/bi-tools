  var listeners = [];

  function has(map, key) {
    return Object.prototype.hasOwnProperty.call(map, key);
  }

  function current() {
    return window.BIToolsI18n.language === "id" ? "id" : "en";
  }

  function translate(text) {
    var value = String(text == null ? "" : text);
    if (current() !== "id") return value;
    return has(id, value) ? id[value] : value;
  }

  function translateServer(text) {
    var value = String(text == null ? "" : text);
    if (current() !== "en" || !value) return value;
    if (has(serverExact, value)) return serverExact[value];
    for (var index = 0; index < serverPatterns.length; index += 1) {
      var pattern = serverPatterns[index][0];
      if (pattern.test(value)) return value.replace(pattern, serverPatterns[index][1]);
    }
    return value;
  }

  function applyAttribute(element, attribute, key, target) {
    if (!element.hasAttribute(attribute)) return;
    var text = element.getAttribute(attribute);
    if (current() === "id" && has(id, text)) {
      text = id[text];
    }
    element.setAttribute(target, text);
  }

  function apply(root) {
    var scope = root || document;
    Array.prototype.forEach.call(scope.querySelectorAll("[data-i18n]"), function (element) {
      var english = element.getAttribute("data-i18n");
      var text = current() === "id" && has(id, english) ? id[english] : english;
      if (element.hasAttribute("data-i18n-html")) {
        element.innerHTML = text;
      } else {
        element.textContent = text;
      }
    });
    Array.prototype.forEach.call(scope.querySelectorAll("[data-i18n-placeholder]"), function (element) {
      applyAttribute(element, "data-i18n-placeholder", "id", "placeholder");
    });
    Array.prototype.forEach.call(scope.querySelectorAll("[data-i18n-title]"), function (element) {
      applyAttribute(element, "data-i18n-title", "id", "title");
    });
    Array.prototype.forEach.call(scope.querySelectorAll("[data-i18n-aria-label]"), function (element) {
      applyAttribute(element, "data-i18n-aria-label", "id", "aria-label");
    });
    Array.prototype.forEach.call(scope.querySelectorAll("[data-i18n-tooltip]"), function (element) {
      applyAttribute(element, "data-i18n-tooltip", "id", "data-tooltip");
    });
  }

  function setLanguage(language, options) {
    var next = language === "id" ? "id" : "en";
    window.BIToolsI18n.language = next;
    document.documentElement.lang = next;
    apply(document);
    (options && options.silent ? [] : listeners).forEach(function (listener) {
      try {
        listener(next);
      } catch (error) {
        return undefined;
      }
      return undefined;
    });
    return next;
  }

  function onChange(listener) {
    if (typeof listener === "function") listeners.push(listener);
  }

